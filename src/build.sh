#!/bin/sh
# Assembles index.html from the source parts. Run from the repository root: sh src/build.sh
# The app loads the atlas point cloud from assets/brain-data.js; the artifact copy (sh src/build.sh artifact OUT) inlines it.
cd "$(dirname "$0")/.." || exit 1
if [ "$1" = "artifact" ]; then
  OUT="${2:-neural-resonance-artifact.html}"
  { sed -n '/<!-- ARTIFACT-START -->/,/<!-- ARTIFACT-END -->/p' index.html | sed '1d;$d' | sed '/<script src="assets\/brain-data.js"><\/script>/{
r assets/brain-data.js
d
}' ; } > "$OUT"
  # the r command places the file after the line; wrap it in a script tag
  python3 - "$OUT" <<'PY'
import sys; p=sys.argv[1]; s=open(p).read()
s=s.replace('// Generated by tools/build-brain-data.py', '<script>\n// Generated by tools/build-brain-data.py',1)
i=s.index('window.BRAIN_BLOB="'); j=s.index('\n', i); s=s[:j]+'\n</script>'+s[j:]
open(p,'w').write(s)
PY
  echo "wrote $OUT"; exit 0
fi
{ cat src/p1_head.html src/p2_body.html; echo '<script src="assets/brain-data.js"></script>'; echo '<script>'; cat src/p3_a.js src/p3_b.js src/p3_c.js src/p3_d.js src/p3_e.js; echo '</script>'; echo '<!-- ARTIFACT-END -->'; echo '</body>'; echo '</html>'; } > index.html
echo "wrote index.html"
